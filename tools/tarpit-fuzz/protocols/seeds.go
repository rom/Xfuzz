// Seed packets, one or more per protocol.
//
// A seed is what a honeypot handler will recognise as the protocol it serves,
// so that byte-level mutations have something to mutate around. They come
// from public specifications and open-source traces: the kind of thing a
// benign network scanner sends on first contact. None of these are complete
// transactions — a complete handshake is what the smart generator builds.
//
// The naming convention is seed<Protocol>, matching the registry's references.
// A seed slice is a []byte for TCP payloads and UDP datagrams alike; the
// engine does not frame them, it writes them as-is.

